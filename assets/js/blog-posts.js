        "text": "更进一步，如果受益者能够运用积累的收入，持续参与政策研究、法律论证和规则修订，取得收益的优势就可能转化为影响制度的优势。经济资源影响规则，规则保障收益，收益再支持对规则的影响，一条能够反复运转的关系便由此形成。它可以通过日常程序逐步维持，无须每一次都发生直接的权钱交易。"
