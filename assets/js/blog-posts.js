      "美国半导体资助提供了可以追踪的例子。2024年资助文件对获得超过1.5亿美元直接资助的项目设置超额收益分享条件；GAO于2026年发布的审查则记录，两个项目的相关安排被删除，另一个项目被修改。[7][8] 从公告到合同，再到后续变更，分配条件并非始终停留在最初文本上。条款变化的原因，还需要结合具体决策材料辨认。",
