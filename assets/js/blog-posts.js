        "type": "paragraph",
        "text": "规则也决定经济资源通过什么渠道进入政治活动。印度选举债券曾允许通过指定银行向政党捐款，而捐款者信息不向公众充分披露。2024年2月，印度最高法院裁定该制度违宪，同时否定允许企业无限额政治捐款的相关法律修改；同年3月，相关银行记录实际公布。这里发生的改变，是政治融资规则及其信息公开条件的改变。[32][33]"
